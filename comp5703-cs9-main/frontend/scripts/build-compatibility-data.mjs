// Build frontend/lib/compatibility/data/generated/*.ts from the CSV sources in
// frontend/lib/compatibility/data/. The CSV files are the source of truth (human-
// maintained); the generated TypeScript modules are what the checks import at
// runtime (a .ts module works unchanged in Next and in `node --test`, a .json
// import would need import attributes in one and resolveJsonModule in the other).
//
//   node scripts/build-compatibility-data.mjs
//
// No dependencies: the parser handles RFC 4180 quoting (double quotes, embedded
// commas and newlines). Every row keeps its column names as keys.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const dataDir = join(here, "..", "lib", "compatibility", "data");
const outDir = join(dataDir, "generated");
mkdirSync(outDir, { recursive: true });

function parseCsv(text) {
  const rows = [];
  let row = [], cell = "", quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"') {
        if (text[i + 1] === '"') { cell += '"'; i++; } else { quoted = false; }
      } else cell += c;
    } else if (c === '"') quoted = true;
    else if (c === ",") { row.push(cell); cell = ""; }
    else if (c === "\n" || c === "\r") {
      if (c === "\r" && text[i + 1] === "\n") i++;
      row.push(cell); rows.push(row); row = []; cell = "";
    } else cell += c;
  }
  if (cell !== "" || row.length) { row.push(cell); rows.push(row); }
  const [header, ...body] = rows.filter((r) => r.length > 1 || r[0] !== "");
  return body.map((r) => Object.fromEntries(header.map((h, i) => [h.replace(/^﻿/, ""), r[i] ?? ""])));
}

// One row per line keeps the generated modules diff-able and reviewable.
const rowsPerLine = (value) =>
  Array.isArray(value)
    ? `[\n${value.map((row) => `  ${JSON.stringify(row)}`).join(",\n")}\n]`
    : `{\n${Object.entries(value).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)}`).join(",\n")}\n}`;
const tsModule = (name, value) =>
  `// Generated by scripts/build-compatibility-data.mjs from ../${name.replace(/_by_name$/, "")}.csv. Do not edit.\n` +
  `export const ${name.replace(/_(\w)/g, (_, c) => c.toUpperCase())} = ${rowsPerLine(value)};\n`;

const files = {
  type_vocabulary: "type_vocabulary.csv",
  type_conversion: "type_conversion.csv",
  semantic_units: "semantic_units.csv",
  field_semantics: "field_semantics.csv",
  invoice_standards: "invoice_standards.csv",
  invoice_standard_exceptions: "invoice_standard_exceptions.csv",
};
const summary = {};
for (const [name, file] of Object.entries(files)) {
  const rows = parseCsv(readFileSync(join(dataDir, file), "utf8"));
  writeFileSync(join(outDir, `${name}.ts`), tsModule(name, rows));
  summary[name] = rows.length;
}
// Index used by S-3: normalized_name -> registry rows. Confirmed rows, plus
// reserved rows: a reserved spelling is registered precisely so that it is
// recognised the first time it appears in the catalogue.
const registry = parseCsv(readFileSync(join(dataDir, files.field_semantics), "utf8"))
  .filter((r) => r.status === "confirmed" || r.status === "reserved");
const byName = {};
for (const r of registry) (byName[r.normalized_name] ??= []).push(r);
writeFileSync(join(outDir, "field_semantics_by_name.ts"), tsModule("field_semantics_by_name", byName));
summary.field_semantics_by_name = Object.keys(byName).length;
console.log(JSON.stringify(summary));
