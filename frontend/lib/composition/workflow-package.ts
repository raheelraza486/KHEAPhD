/**
 * The download behind "Generate AWS workflow": everything one `sam deploy` in
 * AWS CloudShell needs, in one folder named after the workflow, as one zip.
 *
 *   <name>/statemachine.asl.json    the state machine definition (SAM fills in the ARNs)
 *   <name>/statemachine.asl.yaml    the same definition in YAML, for reading
 *   <name>/template.yaml            AWS SAM template: one Lambda function per step and the
 *                                   state machine, wired together with the functions' ARNs
 *   <name>/lambdas/<Function>/...   one folder per function, nothing to install or build:
 *                                   lambda_function.py for an API; index.mjs, its modules
 *                                   (and xmldom) for an adapter step
 *   <name>/make_input.py            turns an invoice file into the execution input
 *   <name>/options.example.json     the adapter step's mapping options, when there is one
 *   <name>/README.txt               the steps, the secrets and parameters, and the warnings
 *
 * The zip is stored without compression: the files are a few hundred
 * kilobytes, and this needs nothing beyond Node's own CRC-32. Server-side only.
 */
import { crc32 } from "node:zlib";

import type { WorkflowBundle } from "./step-functions.ts";

export interface PackageFile {
  path: string;
  content: string;
}

/**
 * Step Functions takes an execution input of at most 256 KB. The first step's result
 * replaces the input (step-functions.ts), so the input itself may come close to it.
 */
const INPUT_LIMIT = 250_000;

const MAKE_INPUT = `#!/usr/bin/env python3
"""Writes the workflow's execution input for an invoice file:

    python3 make_input.py invoice.pdf [options.json] > input.json

A PDF or image goes base64-encoded under "document"; an XML file goes as its text
and a JSON file as its data. options.json, if given, goes under "options" (the
adapter step's mapping options; see options.example.json).
"""
import base64
import json
import sys

LIMIT = ${INPUT_LIMIT}


def main(argv):
    if len(argv) not in (2, 3):
        sys.exit(__doc__)
    with open(argv[1], "rb") as handle:
        data = handle.read()
    try:
        text = data.decode("utf-8-sig")
    except UnicodeDecodeError:
        text = ""
    if text.lstrip().startswith("<"):
        document = text
    elif text.lstrip().startswith(("{", "[")):
        document = json.loads(text)
    else:
        document = base64.b64encode(data).decode()
    payload = {"document": document}
    if len(argv) == 3:
        with open(argv[2], encoding="utf-8") as handle:
            payload["options"] = json.load(handle)
    out = json.dumps(payload)
    if len(out.encode()) > LIMIT:
        sys.exit(f"The input is {len(out.encode())} bytes. Step Functions passes at most 256 KB between states: use a file under about 185 KB.")
    print(out)


if __name__ == "__main__":
    main(sys.argv)
`;

/**
 * What a PDF often does not carry, as /compose/pdf-invoice asks for it. The buyer's electronic
 * address is B2Brouter's sandbox recipient "Test PEPPOL Registered"; over Peppol it must be a
 * participant the sender can reach. seller is needed only when the extraction misses the ABN
 * printed on the invoice; paymentTerms only when the invoice prints neither terms nor a due date.
 * invoiceId, issueDate and dueDate (not in the example) replace the printed number and date, only to
 * re-send an old invoice to a sandbox: B2Brouter refuses a date in a closed fiscal year.
 */
const OPTIONS_EXAMPLE = {
  profile: "pint-aunz",
  buyerReference: "PO-1001",
  paymentTerms: "Payment within 30 days",
  buyer: { endpointId: "9508397101047", endpointSchemeId: "0088", legalRegistrationId: "<buyer ABN>", legalRegistrationSchemeId: "0151" },
  seller: { endpointId: "<seller ABN>", endpointSchemeId: "0151", legalRegistrationId: "<seller ABN>", legalRegistrationSchemeId: "0151" },
};

/**
 * The CloudFormation stack the README deploys, and the deployment id of
 * /api/workflows/deployments (#135): the workflow's name in lower case, always
 * starting with `bp-`, the prefix the site's AWS permissions are scoped to.
 */
export function stackName(bundle: Pick<WorkflowBundle, "name">): string {
  const name = bundle.name.toLowerCase().replace(/[^a-z0-9-]+/g, "-").replace(/-+/g, "-").replace(/^-|-$/g, "");
  return (name.startsWith("bp-") ? name : `bp-${name}`).slice(0, 128).replace(/-$/, "") || "bp-workflow";
}

function readme(bundle: WorkflowBundle): string {
  const stack = stackName(bundle);
  const lines = [
    `${bundle.name}: AWS Step Functions workflow generated by the BP-Builder`,
    "",
    "The workflow, as the Step Functions console draws it:",
    "  Check workflow input   the execution input must carry the document",
    ...bundle.lambdas.map((lambda) => `  ${lambda.state_name}   Lambda ${lambda.function_name}`
      + (lambda.api_id ? ` (${lambda.category}: ${lambda.company_name}, catalogue record ${lambda.api_id})` : ` (${lambda.api_name})`)),
    ...(bundle.lambdas.some((lambda) => lambda.category === "Validation")
      ? ["  Check validation       goes on only if the validator's isValid is true, else Validation failed"]
      : []),
    "  Composition failed     any step's error ends the run here, with that step's error and cause",
    "",
    "Deploy in AWS CloudShell (about five minutes; the client's guide uses ap-southeast-2, Sydney)",
    "",
    "1. In the AWS console, check the region at the top right, then open CloudShell (the >_ icon).",
    `2. Actions -> Upload file -> choose ${bundle.name}.zip. Then:`,
    `     unzip -o ${bundle.name}.zip && cd ${bundle.name}`,
  ];
  if (bundle.secrets.length) {
    lines.push(
      "3. Create the secrets the functions read their credentials from (once per account). Each command",
      "   waits for you to paste the value, which is not shown and is not kept in the shell history:",
      ...bundle.secrets.flatMap((secret) => [
        `     read -rs VALUE && aws secretsmanager create-secret --name ${secret.name} --secret-string "$VALUE"; unset VALUE`,
        `       ${secret.name}: ${secret.value}; read by ${secret.apis.join(", ")}`,
      ]),
      "   To change one later: aws secretsmanager put-secret-value --secret-id <name> --secret-string \"$VALUE\"",
    );
  } else {
    lines.push("3. No secrets: the catalogue records no credential for these APIs.");
  }
  lines.push(
    "4. Deploy (SAM packages the folders as they are; no sam build is needed):",
    "     sam deploy --guided --capabilities CAPABILITY_IAM",
    `   Stack name: ${stack}. Region: the one you are in. Then each parameter:`,
    ...(bundle.parameters.length
      ? bundle.parameters.map((parameter) => `     ${parameter.name}: ${parameter.description}`
        + (parameter.default ? ` (Enter keeps "${parameter.default}")` : "")
        + (parameter.no_echo ? " (hidden as you type)" : ""))
      : ["     (none)"]),
    "   Confirm changes before deploy: y. Allow SAM CLI IAM role creation: Y. Save arguments to a",
    "   configuration file: Y (a later change then needs only `sam deploy`). Deploy this changeset: y.",
    "   The Outputs at the end give StateMachineArn.",
    "5. Run it with an invoice:",
    `     python3 make_input.py invoice.pdf${bundle.uses_options ? " [options.json]" : ""} > input.json`,
    `     aws stepfunctions start-execution --state-machine-arn <StateMachineArn> --input file://input.json`,
    `   or in the console: Step Functions -> State machines -> ${bundle.name} -> Start execution, and paste`,
    "   the contents of input.json. The helper writes inline input (about 185 KB maximum for a PDF).",
    ...(bundle.parameters.some((parameter) => parameter.name === "WorkflowInputBucket") ? [
      "   For PDFs up to 4 MB use Run on AWS on the site after Deploy again: larger PDFs are stored",
      "   privately in WorkflowInputBucket and only a bucket/key reference enters execution history.",
      "   CloudShell can use the same protocol: upload a PDF to <stack>/inputs/<unique-id>.pdf in",
      "   WorkflowInputBucket and set document to {\"s3\":{\"bucket\":\"<bucket>\",\"key\":\"<stack>/inputs/<unique-id>.pdf\"}}.",
      "   Keep options beside document. The bucket must block public access and encrypt objects.",
      "   Configure retention on its inputs prefixes; deleting a workflow does not delete stored PDFs.",
    ] : []),
    "6. Open the execution: Graph view colours each step green or red; select a step to see its input",
    "   and output. Each run calls the real APIs, which may use the providers' credits.",
  );
  if (bundle.uses_options) {
    lines.push(
      "",
      "Mapping options (optional): the adapter step maps the extraction under the profile its",
      "DEFAULT_PROFILE names, and under PINT A-NZ takes an Australian seller's ABN from the invoice, as",
      "/api/composed/pdf-invoice does. What a PDF does not carry (a buyer reference, payment terms,",
      "the buyer's identifiers, the seller's ABN if the extraction misses it) goes in options.json:",
      "copy options.example.json, fill it in or drop what you do not need, and pass it to make_input.py.",
      "For an owner-approved sandbox replay, invoiceId, issueDate and dueDate explicitly replace",
      "those printed fields. Party identities and amounts are unchanged; do not substitute the",
      "sandbox account's ABN for another seller. B2Brouter takes a number once, even after a failed send.",
    );
  }
  lines.push(
    "",
    "Screenshots and recordings: show the Graph view and the steps' output. Do not show Secrets",
    "Manager values, a function's environment variables (they hold the endpoint addresses and the",
    "parameters you entered), or the CloudShell commands where you typed them.",
    "",
    `Remove everything: sam delete --stack-name ${stack}`,
    ...bundle.secrets.map((secret) => `                   aws secretsmanager delete-secret --secret-id ${secret.name}`),
  );
  if (bundle.warnings.length) lines.push("", "Check before deploying:", ...bundle.warnings.map((warning) => `  - ${warning}`));
  lines.push("");
  return lines.join("\n");
}

export function workflowFiles(bundle: WorkflowBundle): PackageFile[] {
  // The definition first: the workflow canvas shows the first .json and the first .yaml file.
  const files: PackageFile[] = [
    { path: "README.txt", content: readme(bundle) },
    { path: "statemachine.asl.json", content: `${bundle.json}\n` },
    { path: "statemachine.asl.yaml", content: bundle.yaml },
    { path: "template.yaml", content: bundle.template_yaml },
    { path: "make_input.py", content: MAKE_INPUT },
    ...(bundle.uses_options ? [{ path: "options.example.json", content: `${JSON.stringify(OPTIONS_EXAMPLE, null, 2)}\n` }] : []),
    ...bundle.lambdas.flatMap((lambda) => lambda.files.map((file) => ({ path: `lambdas/${lambda.function_name}/${file.path}`, content: file.content }))),
  ];
  return files.map((file) => ({ path: `${bundle.name}/${file.path}`, content: file.content }));
}

/**
 * A zip archive of the files, stored (method 0), UTF-8 names. Each entry is
 * marked as a Unix file readable by all (0644), so unzip in CloudShell and
 * Lambda's own extraction give every user read access.
 */
export function zipFiles(files: readonly PackageFile[], date = new Date()): Buffer {
  const time = (date.getHours() << 11) | (date.getMinutes() << 5) | Math.floor(date.getSeconds() / 2);
  const day = ((date.getFullYear() - 1980) << 9) | ((date.getMonth() + 1) << 5) | date.getDate();
  const locals: Buffer[] = [];
  const centrals: Buffer[] = [];
  let offset = 0;
  for (const file of files) {
    const name = Buffer.from(file.path, "utf8");
    const data = Buffer.from(file.content, "utf8");
    const crc = crc32(data);
    const local = Buffer.alloc(30);
    local.writeUInt32LE(0x04034b50, 0);
    local.writeUInt16LE(20, 4);
    local.writeUInt16LE(0x0800, 6);
    local.writeUInt16LE(0, 8);
    local.writeUInt16LE(time, 10);
    local.writeUInt16LE(day, 12);
    local.writeUInt32LE(crc, 14);
    local.writeUInt32LE(data.length, 18);
    local.writeUInt32LE(data.length, 22);
    local.writeUInt16LE(name.length, 26);
    locals.push(local, name, data);

    const central = Buffer.alloc(46);
    central.writeUInt32LE(0x02014b50, 0);
    // Made by Unix (3), version 2.0, so the external attributes below are Unix modes.
    central.writeUInt16LE((3 << 8) | 20, 4);
    central.writeUInt16LE(20, 6);
    central.writeUInt16LE(0x0800, 8);
    central.writeUInt16LE(0, 10);
    central.writeUInt16LE(time, 12);
    central.writeUInt16LE(day, 14);
    central.writeUInt32LE(crc, 16);
    central.writeUInt32LE(data.length, 20);
    central.writeUInt32LE(data.length, 24);
    central.writeUInt16LE(name.length, 28);
    central.writeUInt32LE((0o100644 << 16) >>> 0, 38);
    central.writeUInt32LE(offset, 42);
    centrals.push(central, name);
    offset += local.length + name.length + data.length;
  }
  const directory = Buffer.concat(centrals);
  const end = Buffer.alloc(22);
  end.writeUInt32LE(0x06054b50, 0);
  end.writeUInt16LE(files.length, 8);
  end.writeUInt16LE(files.length, 10);
  end.writeUInt32LE(directory.length, 12);
  end.writeUInt32LE(offset, 16);
  return Buffer.concat([...locals, directory, end]);
}
