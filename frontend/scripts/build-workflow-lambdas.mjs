// Writes lib/composition/workflow-lambda-sources.generated.ts: the group's
// #96 mapping (invoice-mapping.ts, invoice-xml.ts) and the BIS 3.0 copy
// for B2Brouter (peppol-bis3-copy.ts) as plain JavaScript, and
// the @xmldom/xmldom package invoice-xml uses, for the Node.js Lambda functions
// a generated Step Functions workflow runs between Upbrains and AmitTransform
// (#62). The package is carried as files so the deployment package needs no
// `npm install` or `sam build`. Run from frontend after changing either source
// file or the xmldom version:
//
//   node scripts/build-workflow-lambdas.mjs
//
// tests/composition/workflow-lambda-sources.test.ts fails while the generated
// file is out of date, so the Lambdas never drift from the code that runs in
// /api/composed/pdf-invoice.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SOURCES = [
  ["INVOICE_MAPPING_JS", "lib/composition/invoice-mapping.ts"],
  ["INVOICE_XML_JS", "lib/composition/invoice-xml.ts"],
  ["PEPPOL_BIS3_COPY_JS", "lib/composition/peppol-bis3-copy.ts"],
];
export const GENERATED = "lib/composition/workflow-lambda-sources.generated.ts";

function toLambdaModule(file) {
  const output = ts.transpileModule(readFileSync(path.join(root, file), "utf8"), {
    fileName: file,
    compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022, verbatimModuleSyntax: false },
  }).outputText;
  // Sibling imports point at the .mjs files written beside index.mjs in the Lambda.
  return output.replace(/from "\.\/([\w-]+)\.ts"/g, 'from "./$1.mjs"');
}

/** node_modules/@xmldom/xmldom as the application installs it: package.json, LICENSE and lib/*.js. */
function xmldomFiles() {
  const require = createRequire(path.join(root, "package.json"));
  const dir = path.dirname(require.resolve("@xmldom/xmldom/package.json"));
  const pkg = JSON.parse(readFileSync(path.join(dir, "package.json"), "utf8"));
  const files = { "package.json": JSON.stringify({ name: pkg.name, version: pkg.version, main: pkg.main, license: pkg.license }, null, 2) + "\n" };
  files.LICENSE = readFileSync(path.join(dir, "LICENSE"), "utf8").replace(/\r\n/g, "\n");
  for (const name of readdirSync(path.join(dir, "lib")).filter((file) => file.endsWith(".js")).sort()) {
    files[`lib/${name}`] = readFileSync(path.join(dir, "lib", name), "utf8").replace(/\r\n/g, "\n");
  }
  return { version: pkg.version, files };
}

export function renderGenerated() {
  const lines = [
    "// Generated by scripts/build-workflow-lambdas.mjs from invoice-mapping.ts, invoice-xml.ts, peppol-bis3-copy.ts and @xmldom/xmldom. Do not edit.",
    "",
  ];
  for (const [name, file] of SOURCES) lines.push(`export const ${name} = ${JSON.stringify(toLambdaModule(file))};`, "");
  const xmldom = xmldomFiles();
  lines.push(`export const XMLDOM_VERSION = ${JSON.stringify(xmldom.version)};`, "");
  lines.push("/** node_modules/@xmldom/xmldom (MIT), by path inside the package. */");
  lines.push(`export const XMLDOM_FILES: Record<string, string> = ${JSON.stringify(xmldom.files, null, 0)};`, "");
  return lines.join("\n");
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(path.join(root, GENERATED), renderGenerated());
  console.log(`wrote ${GENERATED}`);
}
